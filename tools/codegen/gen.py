def width_of(ch, cat):
    if cat in ("Mn", "Me", "Cf", "Cc", "Cn", "Cs", "Zl", "Zp"):
        return 0
    if unicodedata.east_asian_width(ch) in ("W", "F"):
        return 2
    return 1


def gen_unicode_width():
    """One row per code point, split over plane/part translation units."""
    externs = []
    chunks = []
    total = 0
    plane_counts = {}
    for plane in range(17):
        base = plane << 16
        end = 0x110000 if plane == 16 else base + 0x10000
        part = 0
        pos = base
        while pos < end:
            count = min(CHUNK, end - pos)
            sym = "kWidthP%02dP%02d" % (plane, part)
            rel = "unicode_width_p%02d_%02d.cpp" % (plane, part)
            path = os.path.join(GEN_DIR, rel)
            with open(path + ".tmp", "w", encoding="utf-8", newline="\n") as fh:
                fh.write(BANNER + "\n")
                fh.write('#include "gen_internal.h"\n\n')
                fh.write("namespace vd {\nnamespace gen {\n\n")
                fh.write("extern const CpRecord %s[] = {\n" % sym)
                rows = 0
                for cp in range(pos, pos + count):
                    ch = chr(cp)
                    cat = unicodedata.category(ch)
                    fh.write("{0x%06X,%d,%d},\n" % (cp, width_of(ch, cat), CAT_ID[cat]))
                    rows += 1
                fh.write("};\n\n")
                fh.write("}  // namespace gen\n}  // namespace vd\n")
            os.replace(path + ".tmp", path)
            STATS[rel] = rows + 8
            externs.append("extern const CpRecord %s[];" % sym)
            chunks.append((pos, count, sym))
            total += rows
            plane_counts[plane] = plane_counts.get(plane, 0) + rows
            pos += count
            part += 1
        print("  plane %2d: %6d code points" % (plane, plane_counts[plane]))
    STATS["_width_rows"] = total
    return externs, chunks, total


def gen_width_index(externs, chunks):
    lines = [BANNER, '#include "gen_internal.h"', "", "namespace vd {", "namespace gen {", ""]
    for decl in externs:
        lines.append(decl)
    lines.append("")
    lines.append("namespace {")
    lines.append("")
    lines.append("const ChunkDesc kWidthChunks[] = {")
    for first, count, sym in chunks:
        lines.append("{0x%06Xu, %du, %s}," % (first, count, sym))
    lines.append("};")
    lines.append("")
    lines.append("const std::size_t kWidthChunkCount = sizeof(kWidthChunks) / sizeof(kWidthChunks[0]);")
    lines.append("")
    lines.append("}  // namespace")
    lines.append("")
    lines.append("const char* const kCategoryNames[] = {")
    for name in CATS:
        lines.append('"%s",' % name)
    lines.append("};")
    lines.append("")
    lines.append("const std::size_t kCategoryCount = sizeof(kCategoryNames) / sizeof(kCategoryNames[0]);")
    lines.append("")
    lines.append("int unicode_table_codepoints() { return 0x110000; }")
    lines.append("")
    lines.append("int width_chunk_count() { return static_cast<int>(kWidthChunkCount); }")
    lines.append("")
    lines.append("const ChunkDesc* width_chunks() { return kWidthChunks; }")
    lines.append("")
    lines.append("const CpRecord* width_record(std::uint32_t cp) {")
    lines.append("  if (cp > 0x10FFFFu) return nullptr;")
    lines.append("  std::size_t lo = 0;")
    lines.append("  std::size_t hi = kWidthChunkCount;")
    lines.append("  while (lo + 1 < hi) {")
    lines.append("    const std::size_t mid = (lo + hi) / 2;")
    lines.append("    if (kWidthChunks[mid].first <= cp) {")
    lines.append("      lo = mid;")
    lines.append("    } else {")
    lines.append("      hi = mid;")
    lines.append("    }")
    lines.append("  }")
    lines.append("  const ChunkDesc& desc = kWidthChunks[lo];")
    lines.append("  if (cp < desc.first || cp - desc.first >= desc.count) return nullptr;")
    lines.append("  return &desc.rows[cp - desc.first];")
    lines.append("}")
    lines.append("")
    lines.append("int unicode_width(std::uint32_t cp) {")
    lines.append("  const CpRecord* rec = width_record(cp);")
    lines.append("  return rec == nullptr ? 1 : static_cast<int>(rec->width);")
    lines.append("}")
    lines.append("")
    lines.append("int unicode_category_id(std::uint32_t cp) {")
    lines.append("  const CpRecord* rec = width_record(cp);")
    lines.append("  return rec == nullptr ? 2 : static_cast<int>(rec->cat);")
    lines.append("}")
    lines.append("")
    lines.append("const char* unicode_category(std::uint32_t cp) {")
    lines.append("  const int id = unicode_category_id(cp);")
    lines.append("  if (id < 0 || static_cast<std::size_t>(id) >= kCategoryCount) return kCategoryNames[2];")
    lines.append("  return kCategoryNames[id];")
    lines.append("}")
    lines.append("")
    lines.append("}  // namespace gen")
    lines.append("}  // namespace vd")
    return emit("unicode_width.cpp", lines)


