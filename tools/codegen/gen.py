def glob_match_py(pattern, text):
    p = 0
    t = 0
    star_p = -1
    star_t = -1
    while t < len(text):
        if p < len(pattern) and pattern[p] == "*":
            p += 1
            star_p = p
            star_t = t
            continue
        if p < len(pattern) and (pattern[p] == "?" or pattern[p] == text[t]):
            p += 1
            t += 1
            continue
        if p < len(pattern) and pattern[p] == "[":
            scan = p + 1
            negate = False
            if scan < len(pattern) and pattern[scan] in "!^":
                negate = True
                scan += 1
            hit = False
            closed = False
            while scan < len(pattern):
                if pattern[scan] == "]":
                    closed = True
                    break
                if scan + 2 < len(pattern) and pattern[scan + 1] == "-" and pattern[scan + 2] != "]":
                    if pattern[scan] <= text[t] <= pattern[scan + 2]:
                        hit = True
                    scan += 3
                else:
                    if pattern[scan] == text[t]:
                        hit = True
                    scan += 1
            if closed and (hit != negate):
                p = scan + 1
                t += 1
                continue
        if star_p < 0:
            return False
        p = star_p
        star_t += 1
        t = star_t
    while p < len(pattern) and pattern[p] == "*":
        p += 1
    return p == len(pattern)


def normalize_path_py(path):
    work = path.replace("\\", "/")
    rooted = work.startswith("/")
    out = []
    for part in work.split("/"):
        if part == "" or part == ".":
            continue
        if part == "..":
            if out and out[-1] != "..":
                out.pop()
            elif not rooted:
                out.append("..")
            continue
        out.append(part)
    body = "/".join(out)
    if rooted:
        return "/" + body
    if not body:
        return "."
    return body


def crc64_py(data, table):
    crc = 0
    for byte in data:
        crc = table[(crc ^ byte) & 0xFF] ^ (crc >> 8)
    return crc


def lcg_bytes(seed, length):
    state = seed & 0xFFFFFFFF
    out = bytearray()
    for _ in range(length):
        state = (state * 1103515245 + 12345) & 0xFFFFFFFF
        out.append(((state >> 16) & 0x7FFF) & 0xFF)
    return bytes(out)


