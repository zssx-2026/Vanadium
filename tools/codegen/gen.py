def gen_i18n_catalog():
    data = read_schema("messages.json")
    messages = data["messages"]
    keys = sorted(messages.keys())
    seen = set()
    for key in keys:
        if key in seen:
            raise SystemExit("duplicate message key: " + key)
        seen.add(key)
    lines = [BANNER, '#include "gen_internal.h"', "", "#include <cstring>", ""]
    lines.append("namespace vd {")
    lines.append("namespace gen {")
    lines.append("")
    lines.append("namespace {")
    lines.append("")
