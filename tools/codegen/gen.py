    lines.append("      ++p;")
    lines.append("      ++t;")
    lines.append("      continue;")
    lines.append("    }")
    lines.append("    if (*p == '[') {")
    lines.append("      const char* scan = p + 1;")
    lines.append("      bool negate = false;")
    lines.append("      if (*scan == '!' || *scan == '^') {")
