def collect_unicode_aux():
    named = []
    decomp = []
    ccc = []
    compose = []
    for cp in range(0x110000):
        ch = chr(cp)
        cat = unicodedata.category(ch)
        if cat == "Cn":
            continue
        try:
            nm = unicodedata.name(ch)
        except ValueError:
            nm = None
        if nm:
            named.append((cp, nm))
        cls = unicodedata.combining(ch)
        if cls:
            ccc.append((cp, cls))
        raw = unicodedata.decomposition(ch)
        if raw and not raw.startswith("<"):
            parts = [int(x, 16) for x in raw.split()]
            if len(parts) == 1:
                decomp.append((cp, parts[0], 0))
            elif len(parts) == 2:
                decomp.append((cp, parts[0], parts[1]))
                if unicodedata.normalize("NFC", ch) == ch:
                    compose.append((parts[0], parts[1], cp))
    named.sort()
    decomp.sort()
    ccc.sort()
    compose.sort()
    return named, decomp, ccc, compose


def gen_unicode_names(named):
    externs = []
    chunks = []
    part = 0
    idx = 0
    while idx < len(named):
        rows = named[idx:idx + NAME_CHUNK]
        sym = "kNameChunk%02d" % part
        rel = "unicode_name_%02d.cpp" % part
        lines = [BANNER, '#include "gen_internal.h"', "", "namespace vd {", "namespace gen {", ""]
        lines.append("extern const NameRecord %s[] = {" % sym)
        for cp, nm in rows:
            lines.append("{0x%06X,%s}," % (cp, cxx_string(nm)))
        lines.append("};")
        lines.append("")
        lines.append("}  // namespace gen")
        lines.append("}  // namespace vd")
        emit(rel, lines)
        externs.append("extern const NameRecord %s[];" % sym)
        chunks.append((rows[0][0], rows[-1][0], len(rows), sym))
        idx += NAME_CHUNK
        part += 1
    lines = [BANNER, '#include "gen_internal.h"', "", "namespace vd {", "namespace gen {", ""]
    for decl in externs:
        lines.append(decl)
    lines.append("")
    lines.append("namespace {")
    lines.append("")
    lines.append("const NameChunk kNameChunks[] = {")
    for first, last, count, sym in chunks:
        lines.append("{0x%06Xu, 0x%06Xu, %du, %s}," % (first, last, count, sym))
    lines.append("};")
    lines.append("")
    lines.append("const std::size_t kNameChunkCount = sizeof(kNameChunks) / sizeof(kNameChunks[0]);")
    lines.append("")
    lines.append("}  // namespace")
    lines.append("")
    lines.append("int unicode_name_count() {")
    lines.append("  int total = 0;")
    lines.append("  for (std::size_t i = 0; i < kNameChunkCount; ++i) total += static_cast<int>(kNameChunks[i].count);")
    lines.append("  return total;")
    lines.append("}")
    lines.append("")
    lines.append("const char* unicode_name(std::uint32_t cp) {")
    lines.append("  for (std::size_t i = 0; i < kNameChunkCount; ++i) {")
    lines.append("    const NameChunk& chunk = kNameChunks[i];")
    lines.append("    if (cp < chunk.first || cp > chunk.last) continue;")
    lines.append("    std::size_t lo = 0;")
    lines.append("    std::size_t hi = chunk.count;")
    lines.append("    while (lo < hi) {")
    lines.append("      const std::size_t mid = (lo + hi) / 2;")
    lines.append("      if (chunk.rows[mid].cp == cp) return chunk.rows[mid].name;")
    lines.append("      if (chunk.rows[mid].cp < cp) {")
    lines.append("        lo = mid + 1;")
    lines.append("      } else {")
    lines.append("        hi = mid;")
    lines.append("      }")
    lines.append("    }")
    lines.append("    return nullptr;")
    lines.append("  }")
    lines.append("  return nullptr;")
    lines.append("}")
    lines.append("")
    lines.append("}  // namespace gen")
    lines.append("}  // namespace vd")
    emit("unicode_name.cpp", lines)
    return len(named)


def gen_unicode_nfc(decomp, ccc, compose):
    lines = [BANNER, '#include "gen_internal.h"', "", "#include <algorithm>", "#include <vector>", ""]
    lines.append("namespace vd {")
    lines.append("namespace gen {")
    lines.append("")
    lines.append("namespace {")
    lines.append("")
    lines.append("const DecompRecord kDecomp[] = {")
    for cp, a, b in decomp:
        lines.append("{0x%06X,0x%06X,0x%06X}," % (cp, a, b))
    lines.append("};")
    lines.append("")
    lines.append("const CccRecord kCcc[] = {")
    for cp, cls in ccc:
        lines.append("{0x%06X,%d}," % (cp, cls))
    lines.append("};")
    lines.append("")
    lines.append("const ComposeRecord kCompose[] = {")
    for a, b, cp in compose:
        lines.append("{0x%06X,0x%06X,0x%06X}," % (a, b, cp))
    lines.append("};")
    lines.append("")
    lines.append("const std::size_t kDecompCount = sizeof(kDecomp) / sizeof(kDecomp[0]);")
    lines.append("const std::size_t kCccCount = sizeof(kCcc) / sizeof(kCcc[0]);")
    lines.append("const std::size_t kComposeCount = sizeof(kCompose) / sizeof(kCompose[0]);")
    lines.append("")
    lines.append("const std::uint32_t kSBase = 0xAC00u;")
    lines.append("const std::uint32_t kLBase = 0x1100u;")
    lines.append("const std::uint32_t kVBase = 0x1161u;")
    lines.append("const std::uint32_t kTBase = 0x11A7u;")
    lines.append("const std::uint32_t kLCount = 19u;")
    lines.append("const std::uint32_t kVCount = 21u;")
    lines.append("const std::uint32_t kTCount = 28u;")
    lines.append("const std::uint32_t kNCount = kVCount * kTCount;")
    lines.append("const std::uint32_t kSCount = kLCount * kNCount;")
    lines.append("")
    lines.append("int ccc_of(std::uint32_t cp) {")
    lines.append("  std::size_t lo = 0;")
    lines.append("  std::size_t hi = kCccCount;")
    lines.append("  while (lo < hi) {")
    lines.append("    const std::size_t mid = (lo + hi) / 2;")
    lines.append("    if (kCcc[mid].cp == cp) return static_cast<int>(kCcc[mid].ccc);")
    lines.append("    if (kCcc[mid].cp < cp) {")
    lines.append("      lo = mid + 1;")
    lines.append("    } else {")
    lines.append("      hi = mid;")
    lines.append("    }")
    lines.append("  }")
    lines.append("  return 0;")
    lines.append("}")
    lines.append("")
    lines.append("const DecompRecord* find_decomp(std::uint32_t cp) {")
    lines.append("  std::size_t lo = 0;")
    lines.append("  std::size_t hi = kDecompCount;")
    lines.append("  while (lo < hi) {")
    lines.append("    const std::size_t mid = (lo + hi) / 2;")
    lines.append("    if (kDecomp[mid].cp == cp) return &kDecomp[mid];")
    lines.append("    if (kDecomp[mid].cp < cp) {")
    lines.append("      lo = mid + 1;")
    lines.append("    } else {")
    lines.append("      hi = mid;")
    lines.append("    }")
    lines.append("  }")
    lines.append("  return nullptr;")
    lines.append("}")
    lines.append("")
    lines.append("std::uint32_t compose_pair(std::uint32_t a, std::uint32_t b) {")
    lines.append("  std::size_t lo = 0;")
    lines.append("  std::size_t hi = kComposeCount;")
    lines.append("  while (lo < hi) {")
    lines.append("    const std::size_t mid = (lo + hi) / 2;")
    lines.append("    const ComposeRecord& rec = kCompose[mid];")
    lines.append("    if (rec.first == a && rec.second == b) return rec.composite;")
    lines.append("    if (rec.first < a || (rec.first == a && rec.second < b)) {")
    lines.append("      lo = mid + 1;")
    lines.append("    } else {")
    lines.append("      hi = mid;")
    lines.append("    }")
    lines.append("  }")
    lines.append("  return 0;")
    lines.append("}")
    lines.append("")
    lines.append("void append_decomposed(std::uint32_t cp, std::vector<std::uint32_t>& out, int depth) {")
    lines.append("  if (depth > 32) {")
    lines.append("    out.push_back(cp);")
    lines.append("    return;")
    lines.append("  }")
    lines.append("  if (cp >= kSBase && cp < kSBase + kSCount) {")
    lines.append("    const std::uint32_t index = cp - kSBase;")
    lines.append("    out.push_back(kLBase + index / kNCount);")
    lines.append("    out.push_back(kVBase + (index % kNCount) / kTCount);")
    lines.append("    const std::uint32_t trail = index % kTCount;")
    lines.append("    if (trail != 0) out.push_back(kTBase + trail);")
    lines.append("    return;")
    lines.append("  }")
    lines.append("  const DecompRecord* rec = find_decomp(cp);")
    lines.append("  if (rec == nullptr) {")
    lines.append("    out.push_back(cp);")
    lines.append("    return;")
    lines.append("  }")
    lines.append("  append_decomposed(rec->first, out, depth + 1);")
    lines.append("  if (rec->second != 0) append_decomposed(rec->second, out, depth + 1);")
    lines.append("}")
    lines.append("")
    lines.append("}  // namespace")
    lines.append("")
    lines.append("std::string unicode_normalize_nfc(const std::string& utf8) {")
    lines.append("  std::vector<std::uint32_t> points;")
    lines.append("  points.reserve(utf8.size());")
    lines.append("  const std::size_t len = utf8.size();")
    lines.append("  std::size_t i = 0;")
    lines.append("  while (i < len) {")
    lines.append("    const unsigned char lead = static_cast<unsigned char>(utf8[i]);")
    lines.append("    std::uint32_t cp = lead;")
    lines.append("    std::size_t extra = 0;")
    lines.append("    if (lead < 0x80u) {")
    lines.append("      cp = lead;")
    lines.append("    } else if ((lead & 0xE0u) == 0xC0u) {")
    lines.append("      cp = lead & 0x1Fu;")
    lines.append("      extra = 1;")
    lines.append("    } else if ((lead & 0xF0u) == 0xE0u) {")
    lines.append("      cp = lead & 0x0Fu;")
    lines.append("      extra = 2;")
    lines.append("    } else if ((lead & 0xF8u) == 0xF0u) {")
    lines.append("      cp = lead & 0x07u;")
    lines.append("      extra = 3;")
    lines.append("    } else {")
    lines.append("      cp = 0xFFFDu;")
    lines.append("      extra = 0;")
    lines.append("    }")
    lines.append("    if (i + extra >= len && extra != 0) {")
    lines.append("      points.push_back(0xFFFDu);")
    lines.append("      break;")
    lines.append("    }")
    lines.append("    bool ok = true;")
    lines.append("    for (std::size_t k = 1; k <= extra; ++k) {")
    lines.append("      const unsigned char cont = static_cast<unsigned char>(utf8[i + k]);")
    lines.append("      if ((cont & 0xC0u) != 0x80u) {")
    lines.append("        ok = false;")
    lines.append("        break;")
    lines.append("      }")
    lines.append("      cp = (cp << 6) | (cont & 0x3Fu);")
    lines.append("    }")
    lines.append("    points.push_back(ok ? cp : 0xFFFDu);")
    lines.append("    i += extra + 1;")
    lines.append("  }")
    lines.append("")
    lines.append("  std::vector<std::uint32_t> decomposed;")
    lines.append("  decomposed.reserve(points.size() * 2);")
    lines.append("  for (std::uint32_t cp : points) append_decomposed(cp, decomposed, 0);")
    lines.append("")
    lines.append("  for (std::size_t a = 0; a < decomposed.size(); ++a) {")
    lines.append("    const int cls = ccc_of(decomposed[a]);")
    lines.append("    if (cls == 0) continue;")
    lines.append("    std::size_t b = a;")
    lines.append("    while (b > 0 && ccc_of(decomposed[b - 1]) > cls) {")
    lines.append("      const std::uint32_t tmp = decomposed[b - 1];")
    lines.append("      decomposed[b - 1] = decomposed[b];")
    lines.append("      decomposed[b] = tmp;")
    lines.append("      --b;")
    lines.append("    }")
    lines.append("  }")
    lines.append("")
    lines.append("  std::vector<std::uint32_t> composed;")
    lines.append("  composed.reserve(decomposed.size());")
    lines.append("  for (std::uint32_t cp : decomposed) {")
    lines.append("    if (!composed.empty()) {")
    lines.append("      const std::uint32_t prev = composed.back();")
    lines.append("      std::uint32_t merged = 0;")
    lines.append("      if (prev >= kLBase && prev < kLBase + kLCount && cp >= kVBase && cp < kVBase + kVCount) {")
    lines.append("        merged = kSBase + ((prev - kLBase) * kVCount + (cp - kVBase)) * kTCount;")
    lines.append("      } else if (prev >= kSBase && prev < kSBase + kSCount && ((prev - kSBase) % kTCount) == 0 &&")
    lines.append("                 cp > kTBase && cp < kTBase + kTCount) {")
    lines.append("        merged = prev + (cp - kTBase);")
    lines.append("      } else if (ccc_of(prev) == 0 || ccc_of(cp) == 0) {")
    lines.append("        merged = compose_pair(prev, cp);")
    lines.append("      }")
    lines.append("      if (merged != 0) {")
    lines.append("        composed.back() = merged;")
    lines.append("        continue;")
    lines.append("      }")
    lines.append("    }")
    lines.append("    composed.push_back(cp);")
    lines.append("  }")
    lines.append("")
    lines.append("  std::string out;")
    lines.append("  out.reserve(utf8.size());")
    lines.append("  for (std::uint32_t cp : composed) {")
    lines.append("    if (cp < 0x80u) {")
    lines.append("      out.push_back(static_cast<char>(cp));")
    lines.append("    } else if (cp < 0x800u) {")
    lines.append("      out.push_back(static_cast<char>(0xC0u | (cp >> 6)));")
    lines.append("      out.push_back(static_cast<char>(0x80u | (cp & 0x3Fu)));")
    lines.append("    } else if (cp < 0x10000u) {")
    lines.append("      out.push_back(static_cast<char>(0xE0u | (cp >> 12)));")
    lines.append("      out.push_back(static_cast<char>(0x80u | ((cp >> 6) & 0x3Fu)));")
    lines.append("      out.push_back(static_cast<char>(0x80u | (cp & 0x3Fu)));")
    lines.append("    } else {")
    lines.append("      out.push_back(static_cast<char>(0xF0u | (cp >> 18)));")
    lines.append("      out.push_back(static_cast<char>(0x80u | ((cp >> 12) & 0x3Fu)));")
    lines.append("      out.push_back(static_cast<char>(0x80u | ((cp >> 6) & 0x3Fu)));")
    lines.append("      out.push_back(static_cast<char>(0x80u | (cp & 0x3Fu)));")
    lines.append("    }")
    lines.append("  }")
    lines.append("  return out;")
    lines.append("}")
    lines.append("")
    lines.append("}  // namespace gen")
    lines.append("}  // namespace vd")
    emit("unicode_nfc.cpp", lines)
    return len(decomp), len(ccc), len(compose)


