#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Vanadium generated-code builder.

Reads schema/*.json (the single source of truth) and emits real C++20
translation units into src/gen.  Every emitted file is deterministic:
running the generator twice produces byte-identical output.
"""

import hashlib
import json
import os
import sys
import unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
SCHEMA_DIR = os.path.join(ROOT, "schema")
GEN_DIR = os.environ.get("VD_GEN_DIR") or os.path.join(ROOT, "src", "gen")

CHUNK = 4900           # codepoints per width TU (hard cap: 5000 lines per .cpp)
NAME_CHUNK = 4800      # name rows per TU (hard cap: 5000 lines)

BANNER = "// Generated by tools/codegen/gen.py from schema/*.json. Do not edit by hand."

CATS = [
    "Cc", "Cf", "Cn", "Co", "Cs",
    "Ll", "Lm", "Lo", "Lt", "Lu",
    "Mc", "Me", "Mn", "Nd", "Nl", "No",
    "Pc", "Pd", "Pe", "Pf", "Pi", "Po", "Ps",
    "Sc", "Sk", "Sm", "So",
    "Zl", "Zp", "Zs",
]
CAT_ID = {name: i for i, name in enumerate(CATS)}

STATS = {}


def emit(rel, lines):
    path = os.path.join(GEN_DIR, rel.replace("/", os.sep))
    parent = os.path.dirname(path)
    if parent:
        os.makedirs(parent, exist_ok=True)
    text = "\n".join(lines) + "\n"
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    os.replace(tmp, path)
    STATS[rel] = len(lines)
    return len(lines)


def read_schema(name):
    with open(os.path.join(SCHEMA_DIR, name), "r", encoding="utf-8") as fh:
        return json.load(fh)


def cxx_string(text):
    out = ['"']
    for ch in text:
        code = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif 32 <= code < 127:
            out.append(ch)
        else:
            out.append("\\u%04X" % code if code <= 0xFFFF else "\\U%08X" % code)
    out.append('"')
    return "".join(out)


